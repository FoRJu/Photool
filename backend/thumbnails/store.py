"""
SQLite BLOB-based thumbnail storage.

Replaces individual files on disk with a single SQLite database,
eliminating block-size waste (90GB → ~400MB for 10K thumbnails).

Uses a dedicated database file (separate from catalog) to avoid
lock contention between browsing and thumbnail generation.

Two things this cache has to survive:

  * **An unwritable volume.** The cache normally lives under ``library_root``,
    which is often a secondary drive. If that drive goes read-only, reads still
    work, so the failure is invisible: generation "succeeds" and writes nothing.
    The store now probes write access at startup, serves reads from a read-only
    connection when the probe fails, and raises :class:`CacheNotWritable` on any
    write attempt so callers can report it instead of swallowing it.

  * **Unbounded growth.** A 2000px preview at q90 is ~580 KB, so a few tens of
    thousands of them is tens of gigabytes. Rows now carry their ``source_path``
    and a ``last_access`` stamp, which makes the cache accountable: a size budget
    evicts least-recently-used entries (previews before grids, because grids are
    26 KB and carry the grid view), and a prune can drop rows whose source file
    is gone.
"""

import hashlib
import logging
import os
import sqlite3
import time
from contextlib import contextmanager
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Optional

from storage_health import open_readonly, probe_writable

logger = logging.getLogger(__name__)

_THUMBNAIL_CACHE_VERSION = "v3"

# A cache hit re-stamps last_access at most this often. LRU only has to be
# approximate; writing on every read would cost more than the read it records.
_TOUCH_INTERVAL_SECONDS = 3600

# Eviction deletes in batches rather than one row at a time.
_EVICT_BATCH = 200

# Ask for a VACUUM once eviction has freed this much. Deleting rows frees pages
# into the file's freelist, not back to the disk, so the file stays big until a
# VACUUM rewrites it.
_VACUUM_AFTER_FREED_BYTES = 512 * 1024 * 1024


class ThumbnailSize(Enum):
    GRID = 400
    PREVIEW = 2000
    # What a face is found in. Recognition needs the head to be a decent number
    # of pixels across, and at 400 the same person's scores across one burst
    # span a range that overlaps what two different people score — measured on
    # a real library, same-person 0.61-0.91 at 400 against 0.83-0.98 here. It is
    # generated by the face scan alone, never by the queue, so a library nobody
    # scans pays nothing for it.
    FACE = 1024
    FULL = 0


_JPEG_QUALITY = {
    ThumbnailSize.GRID: 80,
    ThumbnailSize.PREVIEW: 90,
    ThumbnailSize.FACE: 85,
    ThumbnailSize.FULL: 95,
}


class CacheNotWritable(RuntimeError):
    """
    Raised when the cache is asked to write and the write was refused.

    ``transient`` separates a lock the next attempt will get from a volume that
    will not accept writes at all. Without it the queue has one answer for both,
    and the harsher answer is wrong half the time.
    """

    def __init__(self, message: str, transient: bool = False):
        super().__init__(message)
        self.transient = transient


_SCHEMA = """
CREATE TABLE IF NOT EXISTS thumbnails (
    cache_key TEXT NOT NULL,
    size TEXT NOT NULL,
    jpeg_data BLOB NOT NULL,
    byte_length INTEGER NOT NULL,
    created_at TEXT DEFAULT '',
    source_path TEXT DEFAULT '',
    last_access INTEGER DEFAULT 0,
    PRIMARY KEY (cache_key, size)
);

CREATE TABLE IF NOT EXISTS cache_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
"""

# Indexes are created after any column migration, and always with IF NOT EXISTS,
# so they are a no-op on a cache that already has them. They are kept out of
# _SCHEMA because an index on source_path cannot be created on a table that does
# not have that column yet.
_INDEXES = """
CREATE INDEX IF NOT EXISTS idx_thumbnails_size ON thumbnails(size);
CREATE INDEX IF NOT EXISTS idx_thumbnails_source_path ON thumbnails(source_path);
CREATE INDEX IF NOT EXISTS idx_thumbnails_last_access ON thumbnails(last_access);
"""

# Applied to databases created before source_path / last_access existed. Kept as
# explicit statements rather than blind try/except so the one-time cost of an
# ALTER over an existing multi-gigabyte cache can be logged instead of happening
# silently on first startup.
_MIGRATIONS = [
    ("source_path", "ALTER TABLE thumbnails ADD COLUMN source_path TEXT DEFAULT ''"),
    ("last_access", "ALTER TABLE thumbnails ADD COLUMN last_access INTEGER DEFAULT 0"),
]


def _norm_path(path: Path | str) -> str:
    """Stable, comparable absolute path (case-folded on Windows)."""
    return os.path.normcase(os.path.abspath(str(path)))


# A lock is a moment; a read-only volume is a property. "database is locked" and
# "database is busy" mean another connection held the write-lock a beat too long,
# which the next attempt will simply get. Treating either as a verdict about the
# volume latches the cache off forever, and the contradiction that leaves behind
# is the bad part: the queue backs off permanently while a fresh probe of the
# same path reports it perfectly writable, so nothing on screen explains why
# thumbnails stopped.
_TRANSIENT_WRITE_ERRORS = ("database is locked", "database is busy")


def _is_transient_write_error(exc: BaseException) -> bool:
    """True for a refused write that says nothing about the volume."""
    text = str(exc).lower()
    return any(marker in text for marker in _TRANSIENT_WRITE_ERRORS)


class ThumbnailStore:
    """SQLite BLOB-backed thumbnail cache."""

    def __init__(self, db_path: str, max_bytes: int = 0):
        self.db_path = db_path
        self.max_bytes = int(max_bytes or 0)
        self.writable = True
        self.write_error = ""
        self.schema_error = ""
        self._freed_since_vacuum = 0
        self._last_read_error = ""

        # probe_writable creates the parent directory when it can, and reports
        # the reason when it cannot (an ancestor that is a file, a read-only
        # volume). Do not mkdir here: the failure mode is the whole point.
        writable, error = probe_writable(db_path)
        if not writable:
            self.writable = False
            self.write_error = error
            logger.error("[thumbnails] cache is not writable: %s", error)

        self._init_db()

    # ── Setup ────────────────────────────────────────────────────────

    def _init_db(self) -> None:
        if not self.writable:
            # Nothing can be created or migrated. Reads still work, so keep
            # running and let the reported status carry the bad news.
            return
        try:
            with self._connect() as conn:
                conn.executescript(_SCHEMA)
                pending = self._pending_migrations(conn)
                if pending:
                    logger.warning(
                        "[thumbnails] migrating the cache schema at %s — a one-time pass "
                        "over the existing cache, adding %s",
                        self.db_path, ", ".join(name for name, _ in pending),
                    )
                    for _, sql in pending:
                        conn.execute(sql)
                conn.executescript(_INDEXES)
        except sqlite3.OperationalError as exc:
            # The probe passed but SQLite still could not write (a locked file,
            # a WAL it cannot create). Same handling either way.
            self.writable = False
            self.write_error = f"could not initialise the thumbnail cache: {exc}"
            self.schema_error = str(exc)
            logger.error("[thumbnails] %s", self.write_error)

    @staticmethod
    def _pending_migrations(conn: sqlite3.Connection) -> list[tuple[str, str]]:
        """Column additions this database still needs, in order."""
        columns = {row[1] for row in conn.execute("PRAGMA table_info(thumbnails)")}
        return [(name, sql) for name, sql in _MIGRATIONS if name not in columns]

    @contextmanager
    def _connect(self, write: Optional[bool] = None):
        """Open a connection. ``write=False`` opens SQLite in read-only mode."""
        writable = self.writable if write is None else write
        if writable:
            conn = sqlite3.connect(self.db_path)
            conn.execute("PRAGMA journal_mode=WAL")
            conn.execute("PRAGMA synchronous=NORMAL")
        else:
            # A read-only volume refuses the plain open too, because a WAL-mode
            # database needs a writable -shm beside it. open_readonly falls back
            # to immutable mode so cached thumbnails stay readable.
            conn = open_readonly(self.db_path)
        conn.execute("PRAGMA cache_size=-8192")  # 8MB cache
        try:
            yield conn
            if writable:
                conn.commit()
        except Exception:
            if writable:
                conn.rollback()
            raise
        finally:
            conn.close()

    def _readonly(self):
        """Connection for reads when the volume will not allow writes."""
        return self._connect(write=False)

    def _require_writable(self) -> None:
        if not self.writable:
            raise CacheNotWritable(self.write_error or "thumbnail cache is not writable")

    def recheck_writable(self) -> bool:
        """
        Probe the volume again and clear the latch if it accepts writes now.

        A drive that was offline or read-only and has come back should not stay
        latched off until the next restart, and a latch that can only be cleared
        by restarting is not worth having. Re-running the schema pass is safe: it
        is idempotent, and it is the pass that was skipped while writes were off.
        """
        writable, error = probe_writable(self.db_path)
        if not writable:
            self.write_error = error
            return False
        if not self.writable:
            logger.info("[thumbnails] the cache accepts writes again: %s", self.db_path)
            self.writable = True
            self.write_error = ""
            self.schema_error = ""
            self._init_db()
        return True

    def _unreadable(self) -> bool:
        """
        True when there is nothing to read.

        A cache that was never created cannot be opened with mode=ro — SQLite
        fails the open rather than reporting an empty table. Reads then simply
        miss, and the write that follows reports the real problem.
        """
        return not self.writable and not os.path.exists(self.db_path)

    def _log_read_error(self, exc: sqlite3.OperationalError) -> None:
        """Log a read failure once per distinct message, not once per thumbnail."""
        message = str(exc)
        if message != self._last_read_error:
            logger.error("[thumbnails] cannot read the cache at %s: %s", self.db_path, message)
            self._last_read_error = message

    # ── Keys ─────────────────────────────────────────────────────────

    @staticmethod
    def cache_key(source: Path, variant: str = "") -> str:
        """Compute the cache key for a source file.

        ``variant`` names a rendering of the file other than the camera's own —
        today, the file as edited in the develop view. It is part of the key, so
        an edit never overwrites the plain thumbnail, and a changed edit is a
        different key and not a stale hit. An empty variant gives the same key
        the cache has always used.
        """
        stat = source.stat()
        ident = f"{_THUMBNAIL_CACHE_VERSION}:{source}:{stat.st_mtime_ns}:{stat.st_size}"
        if variant:
            ident += f":{variant}"
        return hashlib.sha256(ident.encode()).hexdigest()

    # ── Read / write ─────────────────────────────────────────────────

    def get(self, source: Path, size: ThumbnailSize, variant: str = "") -> Optional[bytes]:
        """Return cached JPEG bytes or None."""
        if self._unreadable():
            return None
        key = self.cache_key(source, variant)
        now = int(time.time())
        conn_ctx = self._connect() if self.writable else self._readonly()
        # last_access is only read to decide whether to re-stamp it, which only
        # makes sense when writes are possible. A cache created before that
        # column existed stays readable while the volume is read-only.
        columns = "jpeg_data, last_access" if self.writable else "jpeg_data"
        try:
            with conn_ctx as conn:
                row = conn.execute(
                    f"SELECT {columns} FROM thumbnails "
                    "WHERE cache_key = ? AND size = ?",
                    (key, size.name.lower()),
                ).fetchone()
                if not row:
                    return None
                last_access = row[1] if self.writable else 0
                if self.writable and now - (last_access or 0) > _TOUCH_INTERVAL_SECONDS:
                    conn.execute(
                        "UPDATE thumbnails SET last_access = ? "
                        "WHERE cache_key = ? AND size = ?",
                        (now, key, size.name.lower()),
                    )
                return row[0]
        except sqlite3.OperationalError as exc:
            # A WAL database on a read-only volume may not be openable at all —
            # SQLite needs a writable -shm beside it. Treat that as a miss; the
            # write path reports the real failure, with the reason.
            self._log_read_error(exc)
            return None

    def has(self, source: Path, size: ThumbnailSize, variant: str = "") -> bool:
        """Check if a thumbnail exists without reading the blob."""
        if self._unreadable():
            return False
        key = self.cache_key(source, variant)
        conn_ctx = self._connect() if self.writable else self._readonly()
        try:
            with conn_ctx as conn:
                row = conn.execute(
                    "SELECT 1 FROM thumbnails WHERE cache_key = ? AND size = ?",
                    (key, size.name.lower()),
                ).fetchone()
                return row is not None
        except sqlite3.OperationalError as exc:
            self._log_read_error(exc)
            return False

    def put(
        self, source: Path, size: ThumbnailSize, jpeg_data: bytes, variant: str = ""
    ) -> None:
        """Store a thumbnail, then keep the cache inside its size budget."""
        self._require_writable()

        key = self.cache_key(source, variant)
        now = datetime.now().isoformat()
        ts = int(time.time())
        source_path = _norm_path(source)
        size_name = size.name.lower()

        try:
            with self._connect() as conn:
                previous = conn.execute(
                    "SELECT byte_length FROM thumbnails WHERE cache_key = ? AND size = ?",
                    (key, size_name),
                ).fetchone()
                conn.execute(
                    """INSERT OR REPLACE INTO thumbnails
                       (cache_key, size, jpeg_data, byte_length, created_at,
                        source_path, last_access)
                       VALUES (?, ?, ?, ?, ?, ?, ?)""",
                    (key, size_name, jpeg_data, len(jpeg_data), now, source_path, ts),
                )
                delta = len(jpeg_data) - (previous[0] if previous else 0)
                rows_delta = 0 if previous else 1
                self._adjust_totals(conn, delta, rows_delta)
                if self.max_bytes:
                    self._enforce_budget(conn)
        except sqlite3.OperationalError as exc:
            if _is_transient_write_error(exc):
                # The volume is fine; this write lost a race for the lock. Say so
                # at warning level and leave the cache marked writable, so the
                # next attempt is a retry rather than a permanent pause.
                logger.warning("[thumbnails] write deferred, cache locked: %s", exc)
                raise CacheNotWritable(f"thumbnail cache is busy: {exc}", transient=True) from exc
            self.writable = False
            self.write_error = f"thumbnail cache write failed: {exc}"
            logger.error("[thumbnails] %s (path: %s)", self.write_error, self.db_path)
            raise CacheNotWritable(self.write_error) from exc

    def delete(self, source: Path) -> int:
        """Remove all thumbnails for a source file."""
        self._require_writable()
        key = self.cache_key(source)
        with self._connect() as conn:
            sizes = [
                row[0] for row in conn.execute(
                    "SELECT byte_length FROM thumbnails WHERE cache_key = ?", (key,)
                )
            ]
            cursor = conn.execute(
                "DELETE FROM thumbnails WHERE cache_key = ?", (key,)
            )
            self._adjust_totals(conn, -sum(sizes), -cursor.rowcount)
            return cursor.rowcount

    # ── Size accounting ──────────────────────────────────────────────

    def _adjust_totals(self, conn: sqlite3.Connection, bytes_delta: int, rows_delta: int) -> None:
        """Keep running totals so the budget check never scans a 13 GB table."""
        if bytes_delta == 0 and rows_delta == 0:
            return
        total_bytes, row_count = self._read_totals(conn, scan=False)
        if total_bytes is None:
            return  # not initialised yet; the next scan-based read seeds it
        conn.executemany(
            "INSERT OR REPLACE INTO cache_meta (key, value) VALUES (?, ?)",
            [("total_bytes", str(max(0, total_bytes + bytes_delta))),
             ("row_count", str(max(0, row_count + rows_delta)))],
        )

    @staticmethod
    def _has_table(conn: sqlite3.Connection, name: str) -> bool:
        return conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?", (name,)
        ).fetchone() is not None

    def _read_totals(self, conn: sqlite3.Connection, scan: bool = True,
                     persist: bool = True) -> tuple[Optional[int], Optional[int]]:
        # A cache created before cache_meta existed has no totals to read, and
        # while the volume is read-only there is no way to add them. Fall back to
        # the full scan, which is correct, just not cheap.
        has_meta = self._has_table(conn, "cache_meta")
        if has_meta:
            meta = dict(conn.execute("SELECT key, value FROM cache_meta").fetchall())
            if "total_bytes" in meta and "row_count" in meta:
                return int(meta["total_bytes"]), int(meta["row_count"])
        if not scan:
            return None, None
        # First use on a cache written before totals existed: one full pass,
        # after which every check is O(1). On a multi-gigabyte cache this reads
        # every page, so say so before it happens.
        logger.info("[thumbnails] computing cache totals for %s (one-time pass)", self.db_path)
        row = conn.execute(
            "SELECT COUNT(*), COALESCE(SUM(byte_length), 0) FROM thumbnails"
        ).fetchone()
        if persist and has_meta:
            conn.executemany(
                "INSERT OR REPLACE INTO cache_meta (key, value) VALUES (?, ?)",
                [("total_bytes", str(row[1])), ("row_count", str(row[0]))],
            )
        return int(row[1]), int(row[0])

    def _enforce_budget(self, conn: sqlite3.Connection) -> None:
        """Evict over budget, least-recently-used first, previews before grids."""
        total_bytes, _ = self._read_totals(conn)
        if total_bytes <= self.max_bytes:
            return

        # Previews are ~20x the size of a grid, so they are where a budget
        # actually buys anything back. Grids are only evicted if previews alone
        # cannot get the cache under the cap.
        passes = [
            "WHERE size = 'preview'",
            "",  # anything left over
        ]
        evicted = 0
        freed_total = 0
        for where in passes:
            while total_bytes > self.max_bytes:
                rows = conn.execute(
                    f"SELECT cache_key, size, byte_length FROM thumbnails "
                    f"{where} ORDER BY last_access ASC, created_at ASC LIMIT {_EVICT_BATCH}"
                ).fetchall()
                if not rows:
                    break

                # One row at a time. Deleting a whole page at once would evict
                # far more than the budget asked for.
                freed = 0
                deleted = 0
                for cache_key, size_name, byte_length in rows:
                    if total_bytes <= self.max_bytes:
                        break
                    conn.execute(
                        "DELETE FROM thumbnails WHERE cache_key = ? AND size = ?",
                        (cache_key, size_name),
                    )
                    total_bytes -= byte_length
                    freed += byte_length
                    deleted += 1

                if deleted:
                    self._adjust_totals(conn, -freed, -deleted)
                    self._freed_since_vacuum += freed
                    evicted += deleted
                    freed_total += freed

        if not evicted:
            return

        logger.warning(
            "[thumbnails] cache over its %s budget: evicted %d least-recently-used "
            "thumbnails (%s) down to %s",
            _fmt_bytes(self.max_bytes), evicted, _fmt_bytes(freed_total),
            _fmt_bytes(total_bytes),
        )
        if self._freed_since_vacuum >= _VACUUM_AFTER_FREED_BYTES:
            logger.warning(
                "[thumbnails] %s freed inside %s — run POST /api/thumbnails/vacuum "
                "to return it to the disk",
                _fmt_bytes(self._freed_since_vacuum), self.db_path,
            )

    def prune(self) -> dict:
        """
        Drop cached thumbnails whose source file no longer exists.

        Rows written before ``source_path`` existed cannot be checked; they are
        counted as ``unverifiable`` and left alone. They sort first under LRU,
        so a configured budget will retire them naturally.
        """
        self._require_writable()
        deleted = 0
        freed = 0
        unverifiable = 0
        with self._connect() as conn:
            rows = conn.execute(
                "SELECT cache_key, size, byte_length, source_path FROM thumbnails"
            ).fetchall()
            stale = []
            for cache_key, size_name, byte_length, source_path in rows:
                if not source_path:
                    unverifiable += 1
                    continue
                if not os.path.exists(source_path):
                    stale.append((cache_key, size_name, byte_length))
            if stale:
                conn.executemany(
                    "DELETE FROM thumbnails WHERE cache_key = ? AND size = ?",
                    [(r[0], r[1]) for r in stale],
                )
                deleted = len(stale)
                freed = sum(r[2] for r in stale)
                self._adjust_totals(conn, -freed, -deleted)
                self._freed_since_vacuum += freed

        result = {
            "deleted": deleted,
            "freed_mb": round(freed / (1024 * 1024), 1),
            "unverifiable": unverifiable,
            "needs_vacuum": self._freed_since_vacuum >= _VACUUM_AFTER_FREED_BYTES,
        }
        if deleted:
            logger.info("[thumbnails] pruned %d orphaned thumbnails (%s)",
                        deleted, _fmt_bytes(freed))
        return result

    # ── Maintenance ──────────────────────────────────────────────────

    def clear(self) -> None:
        """Remove all thumbnails."""
        self._require_writable()
        with self._connect() as conn:
            conn.execute("DELETE FROM thumbnails")
            conn.executemany(
                "INSERT OR REPLACE INTO cache_meta (key, value) VALUES (?, ?)",
                [("total_bytes", "0"), ("row_count", "0")],
            )
        # VACUUM must run outside a transaction
        conn2 = sqlite3.connect(self.db_path)
        conn2.execute("VACUUM")
        conn2.close()

    def _base_stats(self) -> dict:
        """The parts of stats() that do not need to read the cache."""
        return {
            "files": 0,
            "size_mb": 0.0,
            "by_size": {},
            "db_path": self.db_path,
            "writable": self.writable,
            "write_error": self.write_error,
            "max_bytes": self.max_bytes,
            "max_mb": round(self.max_bytes / (1024 * 1024), 1) if self.max_bytes else 0,
            "file_bytes": 0,
            "file_mb": 0.0,
            "freelist_mb": 0.0,
            "unverifiable_rows": 0,
            "needs_vacuum": self._freed_since_vacuum >= _VACUUM_AFTER_FREED_BYTES,
        }

    def count(self, size: str) -> int:
        """How many thumbnails of one size are cached.

        Answered from the index on ``size`` alone. ``stats`` also sums bytes,
        which reads every row and so every stored JPEG — minutes on a cache of
        tens of gigabytes — so anything that asks often asks this instead.
        """
        if self._unreadable():
            return 0
        conn_ctx = self._connect() if self.writable else self._readonly()
        try:
            with conn_ctx as conn:
                return int(conn.execute(
                    "SELECT COUNT(*) FROM thumbnails WHERE size = ?", (size,)
                ).fetchone()[0])
        except sqlite3.OperationalError as exc:
            self._log_read_error(exc)
            return 0

    def stats(self) -> dict:
        """Return storage statistics."""
        stats = self._base_stats()
        if self._unreadable():
            return stats

        conn_ctx = self._connect() if self.writable else self._readonly()
        try:
            with conn_ctx as conn:
                columns = {row[1] for row in conn.execute("PRAGMA table_info(thumbnails)")}
                if not columns:
                    return stats  # no cache table to report on

                total_bytes, total_rows = self._read_totals(conn, persist=self.writable)

                sizes = {}
                for row in conn.execute(
                    "SELECT size, COUNT(*), COALESCE(SUM(byte_length), 0) FROM thumbnails GROUP BY size"
                ).fetchall():
                    sizes[row[0]] = {"count": row[1], "size_mb": round(row[2] / (1024 * 1024), 1)}

                if "source_path" in columns:
                    unverifiable = conn.execute(
                        "SELECT COUNT(*) FROM thumbnails WHERE source_path = '' OR source_path IS NULL"
                    ).fetchone()[0]
                else:
                    # A cache from before source_path existed cannot say which
                    # rows belong to files that are gone. Report them all as
                    # unverifiable; they become checkable once the volume is
                    # writable and the schema migrates.
                    unverifiable = total_rows
        except sqlite3.OperationalError as exc:
            self._log_read_error(exc)
            return stats

        stats["files"] = total_rows
        stats["size_mb"] = round(total_bytes / (1024 * 1024), 1)
        stats["by_size"] = sizes
        stats["unverifiable_rows"] = unverifiable

        try:
            file_bytes = os.path.getsize(self.db_path)
            with self._readonly() as conn:
                page_size = conn.execute("PRAGMA page_size").fetchone()[0]
                freelist = conn.execute("PRAGMA freelist_count").fetchone()[0]
            stats["file_bytes"] = file_bytes
            stats["file_mb"] = round(file_bytes / (1024 * 1024), 1)
            stats["freelist_mb"] = round(page_size * freelist / (1024 * 1024), 1)
        except (OSError, sqlite3.OperationalError):
            pass

        return stats

    def vacuum(self) -> dict:
        """Reclaim unused space."""
        self._require_writable()
        before = os.path.getsize(self.db_path) if os.path.exists(self.db_path) else 0
        with self._connect() as conn:
            conn.execute("VACUUM")
            # Page counts moved, so the cached totals need re-reading next time.
            conn.execute("DELETE FROM cache_meta")
        after = os.path.getsize(self.db_path) if os.path.exists(self.db_path) else 0
        self._freed_since_vacuum = 0
        return {
            "before_mb": round(before / (1024 * 1024), 1),
            "after_mb": round(after / (1024 * 1024), 1),
            "reclaimed_mb": round((before - after) / (1024 * 1024), 1),
        }


def _fmt_bytes(n: int) -> str:
    return f"{n / (1024 * 1024):.0f} MB"
